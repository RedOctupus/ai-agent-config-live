"""agent-memory-design 的评判标准。

四条标准分别看路线、归属与更新、可实施契约、依据标签。
不把论文实验参数或某种固定措辞当成唯一正确答案。
评判器在调用 design_metrics() 时才构造，导入本文件不需要模型密钥。
"""

from deepeval.metrics import GEval
from deepeval.test_case import SingleTurnParams

_PARAMS = [
    SingleTurnParams.INPUT,
    SingleTurnParams.ACTUAL_OUTPUT,
    SingleTurnParams.EXPECTED_OUTPUT,
    SingleTurnParams.CONTEXT,
]


def design_metrics():
    return [
        GEval(
            name="RouteSelection",
            threshold=0.7,
            evaluation_params=_PARAMS,
            evaluation_steps=[
                "先看参考答案的路线：采用更简单的机制、借用部分能力、采用完整逻辑架构，或不进入设计。实际方案必须等价于同一路线。",
                "简单机制的问题不得被升级成四类记忆闭环、图数据库或观点强化。需要长期事实、经历、摘要和可修订判断闭环的问题，不得被降成只查一张当前业务表。",
                "参考答案选中的模块职责必须保留。参考答案暂缓的模块不得列进当前实施范围。模块字母和论文里的四类记忆不要混称。",
                "每个当前要新增的能力都要对应输入里的失败或业务要求。用户只是提到论文有某组件，不能成为采用该组件的理由。",
                "信息不足时允许带假设的初步判断，但只能追问会改变路线或模块的问题，不能先发完整因素表。纯定义问题不得展开成实施方案。",
                "只按路线、模块取舍和有没有多加组件评分。字段命名或段落顺序不同不扣分。",
            ],
        ),
        GEval(
            name="ProvenanceAndUpdate",
            threshold=0.7,
            evaluation_params=_PARAMS,
            evaluation_steps=[
                "一段回答若同时含有事实复述、行动、建议和推断，实际方案必须拆开，不能整段归成一种类型。",
                "「Agent 建议过某判断」不能被写成该判断已经成立。用户接受、实际执行和成功结果必须分开。权威业务状态仍由业务系统裁决。",
                "重试、复述、摘要和多次相同回答继承原证据，不增加独立支持。新的独立事件才按它自己的覆盖范围增加支持。",
                "摘要只从合格且仍然有效的底层记录生成。底层事实或经历的有效变化才重算摘要；观点变化本身不升级为事实。",
                "新增事件、纠正错误、偏好或状态变化、摘要重算、观点修订，按参考答案里真正出现的类型分开处理，不能统一写成最新一句覆盖旧记录。",
                "回答是否再次进入 Retain 必须写成应用接入决定。若进入，必须保留来源和证据依赖。",
            ],
        ),
        GEval(
            name="ExecutableContract",
            threshold=0.7,
            evaluation_params=_PARAMS,
            evaluation_steps=[
                "实际方案要能开工：写清本场景需要的记录职责、谁写入、谁读取、回答如何使用，以及失败时如何降级或回退。字段名可以和参考答案不同。",
                "只推荐摘要时，必须说明事实从哪里来、什么变化使摘要失效。只推荐观点修订时，必须说明新证据如何进入、重复转述如何去重。",
                "有分阶段的第一步，并写明什么观察结果才允许增加下一个能力。",
                "验收是参考答案中的输入序列、预期结果和对照，不是只说运行某个公开 benchmark。需要时说明如何观察正确性、延迟或 token，但不得编造用户没给的数字。",
                "定义题按参考答案停在解释，不因缺少表结构而判失败，也不因额外给出实施方案而判成功。",
            ],
        ),
        GEval(
            name="EvidenceLabels",
            threshold=0.7,
            evaluation_params=_PARAMS,
            evaluation_steps=[
                "容易混淆的设计点要把论文机制、工程扩展和场景假设分开。回流幂等、输入版本和撤回后重算属于工程扩展，不能说成论文已经证明的结论。",
                "RRF 常数、某个重排模型、flan-t5、行为画像 β、每次抽取 2 到 5 条、强化步长若出现，只能作为论文示例或可选实现，不能写成所有项目的硬性要求。",
                "普通全文索引不能被直接说成 BM25。未核验的存储或 SDK 接口要标成示意。信念强度不是已校准的正确概率。",
                "不因为实际方案比参考答案更短就忽略错误的硬性参数。只要把论文示例写成了验收门槛，这一项就应明显扣分。",
            ],
        ),
    ]
