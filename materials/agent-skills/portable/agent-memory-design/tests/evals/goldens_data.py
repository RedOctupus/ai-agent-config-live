def _ordered(names: tuple[str, ...] | list[str]) -> tuple[str, ...]:
    unknown = [name for name in names if name not in MODULES]
    if unknown:
        raise ValueError(f"未知模块: {unknown}")
    return tuple(name for name in MODULES if name in names)


def _line(prefix: str, names: tuple[str, ...]) -> str:
    if not names:
        return f"{prefix}无。"
    return f"{prefix}{'、'.join(names)}。"


def case(
    *,
    name: str,
    family: str,
    route: str,
    selected: tuple[str, ...] | list[str],
    deferred: tuple[str, ...] | list[str],
    failure: str,
    invariant: str,
    user_input: str,
    diagnosis: str,
    why: str,
    contract: str,
    flow: str,
    writeback: str,
    update: str,
    phases: str,
    acceptance: str,
    paper: str,
    engineering: str,
    assumption: str,
    reuse: str,
    questions: tuple[str, ...] = (),
    assumptions: tuple[str, ...] = (),
    graph_failure: str = "",
) -> dict:
    if route not in ROUTE_ZH:
        raise ValueError(route)
    selected_t = _ordered(selected)
    deferred_t = _ordered(deferred)
    overlap = set(selected_t) & set(deferred_t)
    if overlap:
        raise ValueError(f"{name} 选中与暂缓重叠: {overlap}")
    if route == "simple" and selected_t:
        raise ValueError(f"{name} 的 simple 路线不能选中记忆模块")
    if route == "partial" and not selected_t:
        raise ValueError(f"{name} 的 partial 路线必须选中模块")
    if route == "full" and not {"P", "S", "O"} <= set(selected_t):
        raise ValueError(f"{name} 的 full 路线至少要有 P、S、O")
    if route == "out_of_scope" and selected_t:
        raise ValueError(f"{name} 不进入设计时不能选中模块")
    if "G" in selected_t and not graph_failure:
        raise ValueError(f"{name} 选中 G 却没有失败案例")
    if "G" not in selected_t and graph_failure:
        raise ValueError(f"{name} 未选中 G 却写了图失败案例")

    parts = [
        f"诊断：{diagnosis}",
        f"失效位置：{failure}",
        f"路线：{ROUTE_ZH[route]}。{why}",
        _line("选中：", selected_t),
        _line("暂缓：", deferred_t),
        f"复用：{reuse}",
    ]
    if assumptions:
        parts.append("假设：" + "；".join(assumptions) + "。")
    if questions:
        parts.append("只追问：" + "；".join(questions) + "。")
        parts.append("不问完整因素表。这些问题的答案会改变路线或模块，其余缺口保持为假设。")
    if route == "full":
        parts.append(
            "人格与通道：不默认引入行为画像旋钮，也不默认打开全部检索通道或图数据库。"
            "论文里的强化步长、融合常数和具体模型都不是本场景的验收门槛。"
        )
    parts.extend(
        [
            "依据：",
            f"- 论文机制：{paper}",
            f"- 工程扩展：{engineering}",
            f"- 场景假设：{assumption}",
            f"最小契约：{contract}",
            f"读写流程：{flow}",
            f"回答回流：{writeback}",
            f"更新策略：{update}",
            f"分阶段：{phases}",
            f"验收：{acceptance}",
        ]
    )
    expected = "\n".join(parts)
    context = [
        f"路线必须相当于：{ROUTE_ZH[route]}。",
        _line("当前要有的模块职责：", selected_t),
        _line("当前不要引入的模块：", deferred_t),
        f"验收不变式：{invariant}",
        "字段名可以替换。论文里的实验参数、具体模型和示例步长不能写成所有项目的硬性要求。",
        "每个新增模块都要对应本场景的失败或业务要求。没有失败案例的图数据库、全通道检索和行为画像旋钮不要加。",
    ]
    return {
        "name": name,
        "input": user_input.strip(),
        "expected_output": expected,
        "context": context,
        "comments": invariant,
        "source_file": "agent-memory-design/SKILL.md",
        "custom_column_key_values": {
            "route": route,
            "family": family,
            "selected": ",".join(selected_t),
        },
        "additional_metadata": {
            "schema_version": "agent-memory-design-goldens-1",
            "scenario_family": family,
            "route": route,
            "selected": list(selected_t),
            "deferred": list(deferred_t),
            "failure_locus": failure,
            "acceptance_invariant": invariant,
            "questions_that_change_plan": list(questions),
            "assumptions": list(assumptions),
            "graph_failure": graph_failure,
        },
    }


