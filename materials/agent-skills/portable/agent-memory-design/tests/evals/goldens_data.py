def dataset_path() -> Path:
    return Path(__file__).with_name(".dataset.json")


def write_dataset(path: Path | None = None) -> Path:
    target = path or dataset_path()
    target.write_text(
        json.dumps(GOLDENS, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return target


def validate() -> None:
    names = [item["name"] for item in GOLDENS]
    if len(names) != len(set(names)):
        raise ValueError("用例名重复")
    if len(GOLDENS) < 32:
        raise ValueError(f"用例过少: {len(GOLDENS)}")
    inputs = [item["input"] for item in GOLDENS]
    missing = [text for text in PRETEST_INPUTS if text not in inputs]
    if missing:
        raise ValueError(f"缺少技能前测原句: {missing}")
    by_name = {item["name"]: item for item in GOLDENS}
    anchor_sets = []
    for name, (route, selected) in ANCHORS.items():
        item = by_name[name]
        meta = item["additional_metadata"]
        if meta["route"] != route or tuple(meta["selected"]) != tuple(selected):
            raise ValueError(f"锚点不一致: {name}")
        anchor_sets.append(tuple(meta["selected"]))
    if len(set(anchor_sets)) != len(anchor_sets):
        raise ValueError("五个锚点的模块组合必须不同")
    routes = {item["additional_metadata"]["route"] for item in GOLDENS}
    if routes != {"simple", "partial", "full", "out_of_scope"}:
        raise ValueError(routes)
    for item in GOLDENS:
        expected = item["expected_output"]
        for label in ("论文机制：", "工程扩展：", "场景假设：", "验收：", "选中：", "暂缓："):
            if label not in expected:
                raise ValueError(f"{item['name']} 缺少 {label}")


if __name__ == "__main__":
    validate()
    output = write_dataset()
    print(f"{len(GOLDENS)} goldens -> {output}")
